const parsed: Record<string, [number, number][][]> = {};
for (const [k, v] of Object.entries(G)) {
  parsed[k] = v.map((s) => s.split(' ').map((p) => p.split(',').map(Number) as [number, number]));
}

/**
 * Convert text to polylines in board coordinates.
 * (x, y) is the text anchor (centre), h is cap height, rot in degrees CCW.
 */
export function textStrokes(text: string, x: number, y: number, h: number, rot = 0, mirror = false): [number, number][][] {
  const s = h / 6;
  const adv = 5 * s;
  const chars = [...text.toUpperCase().replace(/Ω/g, 'R').replace(/µ|μ/g, 'U')];
  const totalW = chars.length * adv - s;
  const out: [number, number][][] = [];
  const c = Math.cos((rot * Math.PI) / 180);
  const sn = Math.sin((rot * Math.PI) / 180);
  chars.forEach((ch, i) => {
    const g = parsed[ch];
    if (!g) return;
    for (const line of g) {
      out.push(
        line.map(([gx, gy]) => {
          let lx = -totalW / 2 + i * adv + gx * s;
          const ly = -h / 2 + gy * s;
          if (mirror) lx = -lx;
          return [x + lx * c - ly * sn, y + lx * sn + ly * c];
        }),
      );
    }
  });
  return out;
}

export function textWidth(text: string, h: number): number {
  return Math.max(0, [...text].length * (5 * h) / 6 - h / 6);
}
